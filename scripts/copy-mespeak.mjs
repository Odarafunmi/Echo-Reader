// Prepares eSpeak NG (meSpeak.js) for the browser, under /public/mespeak:
//  - mespeak.js: meSpeak's two CommonJS files wrapped into one classic script. It sets window.meSpeak.
//    It is written here, not bundled, because the emscripten build holds stray non-UTF-8 bytes in comments
//    that bundlers refuse to read.
//  - mespeak_config.json and voices/en/en-us.json: the eSpeak data that loadConfig and loadVoice take.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = join(root, 'node_modules', 'mespeak', 'src');
const out = join(root, 'public', 'mespeak');
const data = [
  [join(pkg, 'mespeak_config.json'), join(out, 'mespeak_config.json')],
  [join(root, 'node_modules', 'mespeak', 'voices', 'en', 'en-us.json'), join(out, 'voices', 'en', 'en-us.json')],
];

if (!existsSync(join(pkg, 'index.js')) || !data.every(([src]) => existsSync(src))) {
  console.warn('[copy-mespeak] mespeak not installed yet, skipping.');
  process.exit(0);
}

mkdirSync(join(out, 'voices', 'en'), { recursive: true });
for (const [src, dest] of data) copyFileSync(src, dest);

// Node replaces invalid bytes with U+FFFD. They only appear inside comments.
const espeak = readFileSync(join(pkg, 'ESpeak.js'), 'utf8');
const index = readFileSync(join(pkg, 'index.js'), 'utf8');

const bundle = `/* eSpeak NG via meSpeak.js (GPL). Generated by scripts/copy-mespeak.mjs. Do not edit. */
(function (global) {
  var deps = {};
  function cjs(factory) {
    var m = { exports: {} };
    factory(m, m.exports, function (name) { return deps[name]; });
    return m.exports;
  }
  deps["./ESpeak.js"] = cjs(function (module, exports, require) {
${espeak}
  });
  global.meSpeak = cjs(function (module, exports, require) {
${index}
  });
})(window);
`;
writeFileSync(join(out, 'mespeak.js'), bundle);
console.log('[copy-mespeak] wrote public/mespeak/ (mespeak.js, config, en-us voice)');
